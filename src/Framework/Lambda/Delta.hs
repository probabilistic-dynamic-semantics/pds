-- | Simplify using 'Hspray'.
arithmetic :: DeltaRule
arithmetic t
  | varsOrRats t = do
      result <- toHspray t >>= fromROS vars
      if result == t then Nothing else Just result
  | otherwise = Nothing
  where toHspray  = \case
          Var v    -> (makeVars !!) <$> elemIndex v vars
          DCon x   -> Just (toR x)
          Add t u  -> (+) <$> toHspray t <*> toHspray u
          Neg t    -> (toR 0 -) <$> toHspray t
          Mult t u -> (*) <$> toHspray t <*> toHspray u
          Div t u  -> (/) <$> toHspray t <*> toHspray u
        makeVars  = map makeVar [1..length vars]
        makeVar n = Hspray.lone n Hspray.%//% Hspray.unitSpray
        vars      = sort (nub (freeVars t))
        toR       = toRatio . toRational

toRatio :: Rational -> Hspray.RatioOfSprays Rational
toRatio x = x *> Hspray.unitRatioOfSprays

varsOrRats :: Term -> Bool
varsOrRats = \case
  Var _      -> True
  DCon _     -> True
  Add t u    -> varsOrRats t && varsOrRats u
  Neg t      -> varsOrRats t
  Mult t u   -> varsOrRats t && varsOrRats u
  Div t u    -> varsOrRats t && varsOrRats u
  _          -> False


fromROS :: [String] -> Hspray.RatioOfSprays Rational -- Generated by ChatGPT
        -> Maybe Term
fromROS vars r = do
  num <- fromSpray vars (Hspray._numerator r)
  if Hspray._denominator r == Hspray.unitSpray
    then Just num
    else do
      den <- fromSpray vars (Hspray._denominator r)
      Just (Div num den)


fromSpray :: [String] -> Hspray.Spray Rational -- Generated by ChatGPT
          -> Maybe Term
fromSpray vars spray =
  case sortOn fst (Hspray.toList spray) of
    []    -> Just (DCon 0)
    terms -> foldr1 Add <$> traverse (fromMonomial vars) terms

fromMonomial :: [String] -> ([Int], Rational) -- Generated by ChatGPT
             -> Maybe Term
fromMonomial vars (exps, coeff) = do
  factors <- concat <$> traverse makePower (zip [0..] exps)
  pure $ case factors of
    [] -> DCon (Prel.fromRational coeff)
    _  -> let productTerm = foldl1 Mult factors
          in if coeff == 1
               then productTerm
               else Mult (DCon (Prel.fromRational coeff)) productTerm
  where
    makePower (i, exponent)
      | exponent < 0 = Nothing
      | exponent == 0 = Just []
      | otherwise =
          case drop i vars of
            (name:_) -> Just (replicate exponent (Var name))
            []       -> Nothing

cleanUp :: DeltaRule
cleanUp = \case
  Let v m k | sampleOnly m && v `notElem` freeVars k -> Just k
  _                                                  -> Nothing

-- | Marginalizes out certain distributions; some other stuff.
disjunctions :: DeltaRule
disjunctions = \case
  Let  b (Bern x)     k                     -> Just (Disj x
                                                     (subst b Tr k)
                                                     (subst b Fa k)
                                                    )
  Let  v (Disj x m n) k                     -> Just (Disj x
                                                     (Let v m k)
                                                     (Let v n k)
                                                    )
  Disj x (Let v m k) (Let v' n k') | m == n -> Just (Let v'' m (
                                                        Disj x
                                                          (subst v (Var v'') k)
                                                          (subst v' (Var v'') k')
                                                        )
                                                    )
    where v'':_ = fresh [x, k, k']
  Disj x (Let v (Factor y) t) u             -> Just (factor z (Disj ((x Prel.* y) Prel./ z) (subst v TT t) u))
    where z = x Prel.* y Prel.+ (1 Prel.- x)
  Disj x t (Let v (Factor y) u)             -> Just (factor z (Disj (x Prel./ z) t (subst v TT u)))
    where z = x Prel.+ (1 Prel.- x) Prel.* y
  Disj x m            n            | m == n -> Just m
  Disj x m            Undefined             -> Just (factor x m)
  Disj x Undefined    n                     -> Just (factor (1 Prel.- x) n)
  _                                         -> Nothing

-- | Computes syntactic equalities.
equality :: DeltaRule
equality = \case
  Eq x y | x == y -> Just Tr
  _               -> Nothing

-- | Computes the indicator function.
indicator :: DeltaRule
indicator = \case
  Indi Tr -> Just 1
  Indi Fa -> Just 0
  _       -> Nothing

-- | Computes /if then else/.
ite :: DeltaRule
ite = \case
  ITE Tr x y -> Just x
  ITE Fa x y -> Just y
  _          -> Nothing

logical :: DeltaRule
logical = \case
  And p  Tr -> Just p
  And Tr p  -> Just p
  And Fa _  -> Just Fa
  And _  Fa -> Just Fa
  Or  p  Fa -> Just p
  Or  Fa p  -> Just p
  Or  Tr _  -> Just Tr
  Or  _  Tr -> Just Tr
  _         -> Nothing

-- | Computes the /max/ function.
maxes :: DeltaRule
maxes = \case
   Max (Lam y (GE x (Var y'))) | y' == y
                               , y `notElem` freeVars x -> Just x
   _                                                    -> Nothing          

-- | Observing @Tr@ is trivial, while observing @Fa@ yields an undefined
-- probability distribution.
observations :: DeltaRule
observations = \case
  Let v (Observe Tr) k -> Just (subst v TT k)
  Let _ (Observe Fa) _ -> Just Undefined
  _                    -> Nothing

-- | Computes probabilities.
probabilities :: DeltaRule
probabilities = \case
  Pr t -> Just (TrueMass t Prel./ Mass t)
  _    -> Nothing

-- | Compute masses.
masses :: DeltaRule
masses = \case
  Mass (Return _)               -> Just 1
  Mass (Let v (Factor (Div (DCon 1) (Mass t))) t')
    | t' == t
    , v `notElem` freeVars t'   -> Just 1
  Mass (Let v (Factor x) t)     -> Just (x Prel.* Mass (subst v TT t))
  Mass (Disj x t u)             -> Just (x Prel.* Mass t Prel.+ (1 Prel.- x) Prel.* Mass u)
  Mass Undefined                -> Just 0
  TrueMass (Return Tr)          -> Just 1
  TrueMass (Return Fa)          -> Just 0
  TrueMass (Let v (Factor x) t) -> Just (x Prel.* TrueMass (subst v TT t))
  TrueMass (Disj x t u)         -> Just (x Prel.* TrueMass t Prel.+ (1 Prel.- x) Prel.* TrueMass u)
  TrueMass Undefined            -> Just 0
  _                             -> Nothing

