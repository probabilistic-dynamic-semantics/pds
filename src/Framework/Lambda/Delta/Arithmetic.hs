-- * Arithmetic rules

class Arithmetic simplifier where
  toSimplifier   :: Term -> Maybe simplifier
  fromSimplifier :: Term -> simplifier -> Maybe Term

-- ** Hspray

instance Arithmetic (Hspray.RatioOfSprays Rational) where
  toSimplifier t = case t of
    Add _ _  -> toHspray t
    Neg _    -> toHspray t
    Mult _ _ -> toHspray t
    Div _ _  -> toHspray t
    _        -> Nothing
    where
      toHspray = \case
        DCon x   -> Just (toR x)
        Add t u  -> (+) <$> toHspray t <*> toHspray u
        Neg t    -> (toR 0 -) <$> toHspray t
        Mult t u -> (*) <$> toHspray t <*> toHspray u
        Div t u  -> (/) <$> toHspray t <*> toHspray u
        t        -> (makeVars !!) <$> elemIndex t atoms

      atoms     = arithmeticAtoms t
      makeVars  = map makeVar [1..length atoms]
      makeVar n = Hspray.lone n Hspray.%//% Hspray.unitSpray
      toR       = toRatio . toRational

  fromSimplifier t x = fromROS (arithmeticAtoms t) x


varsOrRats :: Term -> Bool
varsOrRats = \case
  Var _      -> True
  DCon _     -> True
  Add t u    -> varsOrRats t && varsOrRats u
  Neg t      -> varsOrRats t
  Mult t u   -> varsOrRats t && varsOrRats u
  Div t u    -> varsOrRats t && varsOrRats u
  _          -> False


arithmeticAtoms :: Term -> [Term]
arithmeticAtoms = sortOn show . nub . collect
  where
    collect = \case
      DCon _   -> []
      Add t u  -> collect t ++ collect u
      Neg t    -> collect t
      Mult t u -> collect t ++ collect u
      Div t u  -> collect t ++ collect u
      t        -> [t]

toRatio :: Rational -> Hspray.RatioOfSprays Rational
toRatio x = x *> Hspray.unitRatioOfSprays

fromROS :: [Term] -> Hspray.RatioOfSprays Rational -- Generated by ChatGPT
        -> Maybe Term
fromROS vars r = do
  num <- fromSpray vars (Hspray._numerator r)
  if Hspray._denominator r == Hspray.unitSpray
    then Just num
    else do
      den <- fromSpray vars (Hspray._denominator r)
      Just (Div num den)


fromSpray :: [Term] -> Hspray.Spray Rational -- Generated by ChatGPT
          -> Maybe Term
fromSpray vars spray =
  case sortOn fst (Hspray.toList spray) of
    []    -> Just (DCon 0)
    terms -> foldr1 Add <$> traverse (fromMonomial vars) terms

fromMonomial :: [Term] -> ([Int], Rational) -- Generated by ChatGPT
             -> Maybe Term
fromMonomial vars (exps, coeff) = do
  factors <- concat <$> traverse makePower (zip [0..] exps)
  pure $ case factors of
    [] -> DCon (Prel.fromRational coeff)
    _  -> let productTerm = foldl1 Mult factors
          in if coeff == 1
               then productTerm
               else Mult (DCon (Prel.fromRational coeff)) productTerm
  where
    makePower (i, exponent)
      | exponent < 0 = Nothing
      | exponent == 0 = Just []
      | otherwise =
          case drop i vars of
            (t:_) -> Just (replicate exponent t)
            []       -> Nothing
